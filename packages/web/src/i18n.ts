export type Lang = 'ja' | 'en';

export function detectLang(): Lang {
  try {
    const forced = new URLSearchParams(location.search).get('lang');
    if (forced === 'ja' || forced === 'en') return forced;
  } catch {
    /* no location (tests) */
  }
  return typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('ja') ? 'ja' : 'en';
}

let current: Dict = detectLang() === 'ja' ? ja : en;

export function setLang(lang: Lang): void {
  current = lang === 'ja' ? ja : en;
}

/** Translation table; call as `t.key` for strings or `t.key(args)` for formatted ones. */
export const t = new Proxy({} as Dict, {
  get: (_t, key: string) => (current as unknown as Record<string, unknown>)[key],
});
